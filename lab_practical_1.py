import time

# Function for Selection Sort
def selection_sort(arr, n):
    for i in range(n - 1):
        min_index = i

        for j in range(i + 1, n):
            if arr[j] < arr[min_index]:
                min_index = j

        # Swap elements
        temp = arr[i]
        arr[i] = arr[min_index]
        arr[min_index] = temp


